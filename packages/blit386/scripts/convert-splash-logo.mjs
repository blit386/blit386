#!/usr/bin/env node

/**
 * Splash Logo PNG to TypeScript Converter
 *
 * Reads a grayscale-with-alpha (or RGBA) PNG and regenerates
 * src/splash/logoData.ts as a flat row-major array of palette indices into the
 * splash's 16-step ramp.
 *
 * Pixels with alpha at or below ALPHA_THRESHOLD become index 0. Every other pixel is quantized from
 * its luminance onto the ramp: slot RAMP_FIRST_SLOT is the dark end, slot
 * RAMP_LAST_SLOT is the light end.
 *
 * Usage:
 *   pnpm run splash-logo:convert [input-path]
 *
 * Default input: assets/splash-logo.png
 * Output: src/splash/logoData.ts (always overwritten)
 *
 * The generated file is one row per line; run `pnpm run format` afterwards to
 * reflow it the way the committed copy is formatted.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { PNG } from 'pngjs';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = resolve(scriptDir, '..');
const DEFAULT_INPUT = join(PROJECT_ROOT, 'assets/splash-logo.png');
const OUTPUT_PATH = join(PROJECT_ROOT, 'src/splash/logoData.ts');

// Must match src/splash/constants.ts. Duplicated because this is a plain .mjs
// build script and cannot import from TypeScript source.
const RAMP_STEPS = 16;
const RAMP_FIRST_SLOT = 1;

// Rec. 601 luma weights, matching Color32#luminance.
const LUMA_R = 0.299;
const LUMA_G = 0.587;
const LUMA_B = 0.114;

/** Alpha at or below this is treated as fully transparent. */
const ALPHA_THRESHOLD = 8;

/** Channels per pixel in pngjs's normalized RGBA output. */
const CHANNELS = 4;

/**
 * Reads the PNG and quantizes every pixel onto the splash ramp.
 *
 * @param {string} inputPath – Path to the source PNG.
 * @returns {{ width: number, height: number, indices: number[] }} Dimensions and flat index array.
 */
function extractIndices(inputPath) {
    const png = PNG.sync.read(readFileSync(inputPath));
    const indices = new Array(png.width * png.height);

    /* eslint-disable security/detect-object-injection -- bounded loop counters over our own buffers */
    for (let i = 0; i < indices.length; i++) {
        const offset = i * CHANNELS;
        const alpha = png.data[offset + 3];

        if (alpha <= ALPHA_THRESHOLD) {
            indices[i] = 0;
            continue;
        }

        const luma = (LUMA_R * png.data[offset] + LUMA_G * png.data[offset + 1] + LUMA_B * png.data[offset + 2]) / 255;
        const step = Math.min(RAMP_STEPS - 1, Math.max(0, Math.round(luma * (RAMP_STEPS - 1))));

        indices[i] = RAMP_FIRST_SLOT + step;
    }
    /* eslint-enable security/detect-object-injection */

    return { width: png.width, height: png.height, indices };
}

/**
 * Renders the generated TypeScript module.
 *
 * @param {{ width: number, height: number, indices: number[] }} data – Extracted logo data.
 * @returns {string} File contents.
 */
function renderModule(data) {
    const rows = [];

    for (let y = 0; y < data.height; y++) {
        const row = data.indices.slice(y * data.width, (y + 1) * data.width);

        rows.push(`    ${row.join(', ')},`);
    }

    return `/**
 * Inline row-major palette indices for the BLIT386 splash logo.
 *
 * Generated by \`node scripts/convert-splash-logo.mjs\` from
 * \`assets/splash-logo.png\`. Do not hand-edit: regenerate instead.
 *
 * \`0\` is transparent; every other value indexes the splash's gray ramp
 * (see \`src/splash/constants.ts\`).
 */

/** Splash logo width in pixels. */
export const LOGO_WIDTH = ${data.width};

/** Splash logo height in pixels. */
export const LOGO_HEIGHT = ${data.height};

/**
 * Row-major palette indices (\`LOGO_WIDTH\` x \`LOGO_HEIGHT\`).
 */
export const LOGO_PIXELS: readonly number[] = [
${rows.join('\n')}
];
`;
}

const inputPath = process.argv[2] ?? DEFAULT_INPUT;
const data = extractIndices(inputPath);

writeFileSync(OUTPUT_PATH, renderModule(data), 'utf-8');

console.log(`Wrote ${OUTPUT_PATH} (${data.width}x${data.height}, ${data.indices.length} indices)`);
